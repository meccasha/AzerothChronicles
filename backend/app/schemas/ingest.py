"""Normalized ingestion envelope shared by the WoW addon export, the companion uploader
and simulated events. See docs/ingestion-format.md."""

from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field

INGEST_FORMAT = "azeroth-chronicles/v1"


class _Rec(BaseModel):
    model_config = ConfigDict(extra="ignore")

    id: str = Field(min_length=1, max_length=120, description="Stable id generated by the source")
    character_guid: str | None = Field(default=None, max_length=64)
    character_name: str | None = Field(default=None, max_length=32)
    character_realm: str | None = Field(default=None, max_length=64)


class RosterEntry(BaseModel):
    model_config = ConfigDict(extra="ignore")
    name: str = Field(max_length=32)
    realm: str | None = Field(default=None, max_length=64)
    guid: str | None = Field(default=None, max_length=64)


class EncounterRecord(_Rec):
    type: Literal["encounter"]
    encounter_id: int = Field(description="DungeonEncounterID from ENCOUNTER_END")
    encounter_name: str = Field(max_length=160)
    instance_name: str | None = Field(default=None, max_length=160)
    instance_id: int | None = None
    instance_type: Literal["raid", "party", "scenario", "other"] = "raid"
    difficulty_id: int | None = None
    difficulty_name: str | None = Field(default=None, max_length=64)
    group_size: int | None = Field(default=None, ge=1, le=40)
    success: bool
    start_time: int | None = Field(default=None, description="Unix seconds (GetServerTime)")
    end_time: int
    roster: list[RosterEntry] = Field(default_factory=list, max_length=40)
    # Personal deaths observed via PLAYER_DEAD during the encounter; null = not tracked.
    deaths: int | None = Field(default=None, ge=0, le=100)


class AchievementRecord(_Rec):
    type: Literal["achievement"]
    achievement_id: int
    name: str = Field(max_length=200)
    points: int = Field(default=0, ge=0, le=500)
    description: str | None = Field(default=None, max_length=1000)
    feat_of_strength: bool = False
    earned_at: int


class LootRecord(_Rec):
    type: Literal["loot"]
    item_id: int
    item_name: str = Field(max_length=200)
    quality: int = Field(ge=0, le=8)
    item_class: str | None = Field(default=None, max_length=64)
    item_subclass: str | None = Field(default=None, max_length=64)
    item_level: int | None = Field(default=None, ge=0, le=2000)
    icon: str | None = Field(default=None, max_length=200)
    encounter_id: int | None = None
    instance_name: str | None = Field(default=None, max_length=160)
    difficulty_name: str | None = Field(default=None, max_length=64)
    looted_at: int


class CollectibleRecord(_Rec):
    type: Literal["mount", "pet", "toy"]
    collectible_id: int
    name: str = Field(max_length=200)
    item_id: int | None = None
    learned_at: int


class DungeonRecord(_Rec):
    type: Literal["dungeon_complete"]
    map_id: int
    name: str = Field(max_length=160)
    keystone_level: int | None = Field(default=None, ge=0, le=50)
    on_time: bool | None = None
    completed_at: int
    duration_ms: int | None = None
    roster: list[RosterEntry] = Field(default_factory=list, max_length=5)


IngestRecord = Annotated[
    EncounterRecord | AchievementRecord | LootRecord | CollectibleRecord | DungeonRecord,
    Field(discriminator="type"),
]


class CharacterInfo(BaseModel):
    model_config = ConfigDict(extra="ignore")
    guid: str = Field(max_length=64)
    name: str = Field(max_length=32)
    realm: str = Field(max_length=64)
    region: str = Field(default="us", max_length=8)
    class_name: str | None = Field(default=None, alias="class", max_length=32)
    race: str | None = Field(default=None, max_length=32)
    faction: str | None = Field(default=None, max_length=16)
    level: int | None = Field(default=None, ge=1, le=100)
    spec: str | None = Field(default=None, max_length=32)


class IngestEnvelope(BaseModel):
    model_config = ConfigDict(extra="ignore")
    format: Literal["azeroth-chronicles/v1"] = INGEST_FORMAT
    source: Literal["addon", "companion", "simulated"] = "addon"
    addon_version: str | None = Field(default=None, max_length=32)
    exported_at: int | None = None
    characters: list[CharacterInfo] = Field(default_factory=list, max_length=200)
    records: list[IngestRecord] = Field(default_factory=list, max_length=20000)


class IngestResult(BaseModel):
    received: int
    normalized: int
    duplicates: int
    ignored: int
    rejected: int
    events_created: int
    events_merged: int
    groups: list[str]
    messages: list[str] = Field(default_factory=list)
    sync_job_id: str
